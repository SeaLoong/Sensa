import { execFileSync } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { test, expect, oscWorkspace, mode, selectMappingPreset } from './fixtures.js';

test.use({launchOptions:{args:['--disable-features=Translate']}});
test('capture recommended scenarios and standard axis checks', async ({page}) => {
  const dir = 'artifacts/preset-interaction';
  await mkdir(dir, { recursive: true });
  await mode(page, 'OSC'); await oscWorkspace(page, '映射');
  const select = page.getByLabel('预设方案', {exact:true});
  await selectMappingPreset(page, 'sps-limited');
  await expect(select.locator('optgroup[label="推荐预设"] option')).toHaveCount(4);
  await expect(select.locator('optgroup[label="标准预设"] option')).toHaveCount(16);
  await select.focus(); await select.press('Alt+ArrowDown'); await page.waitForTimeout(350);
  execFileSync('import',['-window','root','-crop','1020x1050+226+20','+repage',dir+'/preset-groups.png']);
  await page.keyboard.press('Escape');
  const conditions = page.getByTestId('axis-mappings-panel').getByTestId('preset-requirements');
  await select.selectOption('native-contact-axial');
  await expect(conditions).toContainText('SenderLocalPosition');
  await conditions.screenshot({path:dir+'/contact-requirements.png'});
  await expect(select.locator('option[value="self-contact-stroke"]')).toHaveCount(0);
  await select.selectOption('pose-six-axis');
  await expect(conditions).toContainText('receiveOthers');
  await conditions.screenshot({path:dir+'/pose-requirements.png'});
  await page.getByRole('button',{name:'替换草稿',exact:true}).click();
  await expect(page.locator('.mapping-row__target select')).toHaveCount(6);
  await expect(page.locator('.toast')).toHaveCount(0);
  await page.screenshot({path:dir+'/six-axis.png'});
  await select.selectOption({label:'横移时保持深度 · 跟随平面…'});
  const plane=page.getByTestId('computed-spatial-presets');
  await plane.getByLabel('测量对象路径',{exact:true}).fill('Sensa/Contact/Target/**');
  await plane.getByLabel('平面参考对象路径',{exact:true}).fill('Sensa/Contact/Guide_Origin/**');
  await plane.getByRole('button',{name:'将平面深度设为 L0（替换主轴草稿）',exact:true}).click();
  const rows=page.locator('.mapping-row');
  await expect(rows).toHaveCount(6);
  const depth=rows.filter({has:page.locator('.mapping-row__target option[value="Depth"]:checked')});
  await expect(depth.getByLabel('输入类型',{exact:true})).toHaveValue('Computed');
});
